export async function initializeDatabase(forceReset = false) {
  const settingsCount = await db.settings.count();

  if (settingsCount === 0 || forceReset) {
    await db.transaction(
      'rw',
      [
        db.members,
        db.cards,
        db.services,
        db.budgets,
        db.goals,
        db.subscriptions,
        db.transactions,
        db.calendarEvents,
        db.notifications,
        db.settings,
      ],
      async () => {
        if (forceReset) {
          await db.members.clear();
          await db.cards.clear();
          await db.services.clear();
          await db.budgets.clear();
          await db.goals.clear();
          await db.subscriptions.clear();
          await db.transactions.clear();
          await db.calendarEvents.clear();
          await db.notifications.clear();
          await db.settings.clear();
        }

        await db.members.bulkAdd(INITIAL_MEMBERS);
        await db.cards.bulkAdd(INITIAL_CARDS);
        await db.services.bulkAdd(INITIAL_SERVICES);
        await db.budgets.bulkAdd(INITIAL_BUDGETS);
        await db.goals.bulkAdd(INITIAL_GOALS);
        await db.subscriptions.bulkAdd(INITIAL_SUBSCRIPTIONS);
        await db.transactions.bulkAdd(INITIAL_TRANSACTIONS);
        await db.calendarEvents.bulkAdd(INITIAL_CALENDAR_EVENTS);
        await db.notifications.bulkAdd(INITIAL_NOTIFICATIONS);
        await db.settings.add(INITIAL_SETTINGS);
      }
    );
  }
}
