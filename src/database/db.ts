import Dexie, { type Table } from 'dexie';
import {
  Transaction,
  PaymentCard,
  UtilityService,
  Budget,
  FamilyGoal,
  Subscription,
  CalendarEvent,
  AppNotification,
  FamilyMember,
  FamilySettings,
} from '../types';

export class BarakaDatabase extends Dexie {
  transactions!: Table<Transaction, string>;
  cards!: Table<PaymentCard, string>;
  services!: Table<UtilityService, string>;
  budgets!: Table<Budget, string>;
  goals!: Table<FamilyGoal, string>;
  subscriptions!: Table<Subscription, string>;
  calendarEvents!: Table<CalendarEvent, string>;
  notifications!: Table<AppNotification, string>;
  members!: Table<FamilyMember, string>;
  settings!: Table<FamilySettings, string>;

  constructor() {
    super('BarakaFinanceDB');

    this.version(1).stores({
      transactions: 'id, type, category, date, memberId, cardId, linkedPaymentId, linkedSubscriptionId, createdAt',
      cards: 'id, nickname, cardType, isDefault',
      services: 'id, category, status, dueDate',
      budgets: 'id, category, month',
      goals: 'id, isCompleted',
      subscriptions: 'id, status, nextBillingDate',
      calendarEvents: 'id, date, type, isCompleted',
      notifications: 'id, isRead, date',
      members: 'id, role',
      settings: 'id',
    });
  }
}

